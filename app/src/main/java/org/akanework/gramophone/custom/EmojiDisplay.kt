    private const val EMOJI_ENABLED = "emoji_enabled"

    // New installs show emojis by default. Switch off under hidden PIN-protected menu.
    fun isEnabled(context: Context): Boolean =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getBoolean(EMOJI_ENABLED, true)

    fun setEnabled(context: Context, enabled: Boolean) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit()
            .putBoolean(EMOJI_ENABLED, enabled).apply()
    }

    fun display(context: Context, value: CharSequence?): String {
        val original = value?.toString().orEmpty()
        return if (isEnabled(context)) convertText(original) else original
    }

